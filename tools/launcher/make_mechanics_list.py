#!/usr/bin/env python3
"""Builds tools/launcher/mechanics.json5: the bool settings this branch added to specs/config/main.json5
against `main`, grouped by documentation category, in schema order.

    python tools/launcher/make_mechanics_list.py [--base main] [--out tools/launcher/mechanics.json5]

Left out: settings the launcher already handles with its own widgets (HANDLED below), and bool settings
whose default is true (the launcher only writes `= true;` lines). Int and enum settings are a later piece.
Run it from the repository root; needs git.
"""
import argparse
import re
import subprocess
import sys

SCHEMA = "specs/config/main.json5"

# Written by launcher_config.cpp's own widgets (Build_User_Cfg): they stay there.
HANDLED = {
    ("advisor", "enabled"),
    ("advisor", "rules_spies"),
    ("advisor", "rules_expansion"),
    ("advisor", "rules_outposts"),
    ("advisor", "rules_objectives"),
    ("advisor", "rules_exploration"),
    ("advisor", "rules_lanchester"),
    ("advisor", "rules_counter_design"),
    ("advisor", "rules_seen_ships"),
    ("advisor", "rules_race"),
    ("advisor", "rules_balance"),
    ("advisor", "rules_doctrine"),
    ("advisor", "rules_phases"),
    ("ai", "research_uses_own_output"),
    ("diplomacy", "memory"),
}


def parameters(text):
    lines = text.split("\n")
    start = lines.index("  parameters: {")
    result = []
    current = None
    for line in lines[start + 1:]:
        if line == "  },":
            break
        m = re.match(r"^    (\w+): \{", line)
        if m:
            current = {"name": m.group(1)}
            result.append(current)
            continue
        m = re.match(r"^      (\w+): (.*?),?$", line)
        if m and current is not None and m.group(1) in ("namespace", "type", "default", "title"):
            current.setdefault(m.group(1), m.group(2).strip().strip('"'))
    return result


def categories(text):
    """[(id, title, [namespaces])] in schema order."""
    lines = text.split("\n")
    start = lines.index("  documentation_categories: {")
    result = []
    for line in lines[start + 1:]:
        if line == "  },":
            break
        m = re.match(r"^    (\w+): \{", line)
        if m:
            result.append([m.group(1), "", []])
            continue
        m = re.match(r'^      title: "(.*)",$', line)
        if m and result:
            result[-1][1] = m.group(1)
        m = re.match(r"^      namespaces: \[(.*)\],$", line)
        if m and result:
            result[-1][2] = re.findall(r'"(\w+)"', m.group(1))
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="main")
    ap.add_argument("--out", default="tools/launcher/mechanics.json5")
    args = ap.parse_args()

    old_text = subprocess.run(["git", "show", f"{args.base}:{SCHEMA}"], check=True, capture_output=True).stdout.decode("utf-8")
    with open(SCHEMA, encoding="utf-8", newline="") as f:
        new_text = f.read()
    old_keys = {(p.get("namespace"), p["name"]) for p in parameters(old_text)}
    added = [p for p in parameters(new_text) if (p.get("namespace"), p["name"]) not in old_keys]

    cats = categories(new_text)
    ns_to_cat = {ns: i for i, c in enumerate(cats) for ns in c[2]}
    groups = {i: [] for i in range(len(cats))}
    skipped_true = []
    for p in added:
        ns = p.get("namespace")
        if p.get("type") != "bool" or (ns, p["name"]) in HANDLED:
            continue
        if p.get("default") != "false":
            skipped_true.append(f"{ns} {p['name']}")
            continue
        groups[ns_to_cat[ns]].append((ns, p["name"]))

    out = [
        "// Generated by tools/launcher/make_mechanics_list.py from `git diff main -- specs/config/main.json5`:",
        "// the bool settings this branch added, by documentation category, in schema order.",
        "// Titles and descriptions come from settings_catalog.json at run time.",
        "{",
        "  categories: [",
    ]
    for i, c in enumerate(cats):
        if not groups[i]:
            continue
        out.append("    {")
        out.append(f'      id: "{c[0]}",')
        out.append(f'      title: "{c[1]}",')
        out.append("      settings: [")
        for ns, name in groups[i]:
            out.append(f'        {{ namespace: "{ns}", name: "{name}" }},')
        out.append("      ],")
        out.append("    },")
    out.append("  ],")
    out.append("}")
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    total = sum(len(g) for g in groups.values())
    print(f"{total} settings in {sum(1 for g in groups.values() if g)} categories -> {args.out}")
    for i, c in enumerate(cats):
        if groups[i]:
            print(f"  {c[0]}: {len(groups[i])}")
    if skipped_true:
        print("skipped (default true): " + ", ".join(skipped_true))


if __name__ == "__main__":
    sys.exit(main())
